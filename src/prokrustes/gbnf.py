"""GBNF emission helpers.

Only three things are needed to turn a regex into a grammar: quoting literal
text, naming rules legally, and checking the result parses. The grammar dialect
is llama.cpp's, whose escape set and rule-name rules are narrow -- see
``regexgbnf`` for what that rules out.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field


class GrammarError(Exception):
    pass


_ESCAPES = {
    "\\": "\\\\",
    '"': '\\"',
    "\n": "\\n",
    "\r": "\\r",
    "\t": "\\t",
}


def gbnf_literal(text: str) -> str:
    """Quote arbitrary text as a GBNF terminal string."""
    out = ['"']
    for ch in text:
        esc = _ESCAPES.get(ch)
        if esc is not None:
            out.append(esc)
        elif ch < " " or ch == "\x7f":
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def check_syntax(text: str) -> None:
    """Reject grammars with unbalanced groups or unterminated string literals.

    A stray ``)`` typed inside a quoted terminal is easy to introduce, and
    llama-server reports it only as "failed to parse grammar" with no line
    number, so it is worth catching before the request is made.
    """
    depth = 0
    in_string = False
    line = 1
    index = 0
    while index < len(text):
        ch = text[index]
        if in_string:
            if ch == "\\":
                index += 2
                continue
            if ch == '"':
                in_string = False
            elif ch == "\n":
                line += 1
            index += 1
            continue
        if ch == "\n":
            line += 1
        elif ch == '"':
            in_string = True
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth < 0:
                raise GrammarError(
                    "unbalanced ')' near line %d: a closing paren appears inside "
                    "a quoted terminal" % line
                )
        index += 1
    if in_string:
        raise GrammarError("unterminated string literal in generated grammar")
    if depth != 0:
        raise GrammarError(
            "unbalanced '(' in generated grammar (%d group(s) left open)" % depth
        )


def has_unbounded_repetition(expr: str) -> bool:
    """Whether a rule contains a ``*`` or ``+`` repetition.

    A small model will happily emit ``[a-z0-9]+`` forever, and the document it
    produces then gets truncated mid-value. Bounding the repetition keeps
    generation inside the template, so callers warn rather than discover this as
    a mysteriously truncated file.
    """
    in_string = False
    in_class = False
    index = 0
    while index < len(expr):
        ch = expr[index]
        if in_string:
            if ch == "\\":
                index += 2
                continue
            if ch == '"':
                in_string = False
        elif in_class:
            if ch == "]":
                in_class = False
        elif ch == '"':
            in_string = True
        elif ch == "[":
            in_class = True
        elif ch in "*+":
            return True
        index += 1
    return False


def rule_name(raw: str, taken: set[str]) -> str:
    """Derive a legal, unique GBNF rule name from a field name.

    GBNF rule names match ``[a-zA-Z0-9-]`` -- underscore is not allowed, so
    ``api_key`` has to become ``api-key``.
    """
    slug = re.sub(r"[^a-z0-9]+", "-", raw.lower()).strip("-")
    if not slug:
        slug = "field"
    if not slug[0].isalpha():
        slug = "v" + slug
    name = "v-" + slug
    if name in taken:
        n = 2
        while "%s-%d" % (name, n) in taken:
            n += 1
        name = "%s-%d" % (name, n)
    taken.add(name)
    return name


@dataclass
class Grammar:
    """Accumulates rules, emitting shared primitives before their users."""

    prims: dict[str, str] = field(default_factory=dict)
    rules: dict[str, str] = field(default_factory=dict)
    used: set[str] = field(default_factory=set)

    def prim(self, name: str, body: str) -> str:
        self.prims.setdefault(name, body)
        self.used.add(name)
        return name

    def add(self, name: str, body: str) -> str:
        if name in self.rules:
            raise GrammarError("duplicate rule name %r" % name)
        self.rules[name] = body
        return name

    def render(self, root_body: str) -> str:
        text = "\n".join(
            ["%s ::= %s" % (n, b) for n, b in self.prims.items()]
            + ["%s ::= %s" % (n, b) for n, b in self.rules.items()]
            + ["root ::= %s" % root_body]
        )
        check_syntax(text)
        out = ["# generated by prokrustes", ""]
        for name, body in self.prims.items():
            if name in self.used:
                out.append("%s ::= %s" % (name, body))
        out.append("")
        for name, body in self.rules.items():
            out.append("%s ::= %s" % (name, body))
        out.append("")
        out.append("root ::= %s" % root_body)
        out.append("")
        return "\n".join(out)
